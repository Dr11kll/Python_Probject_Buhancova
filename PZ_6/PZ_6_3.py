# Дан список размера N и целое число K (1 < K < N). Осуществить сдвиг элементов
# список вправо на K позиций (при этом A1 перейдет в AK+1, A2 — в AK+2, ..AN-K — в
# AN, а исходное значение K последних элементов будет потеряно). Первые K
# элементов полученного списка положить равными 0.
import random
# Вводим размер списка
n = int(input('Введи размер массива: '))
# Вводим количество позиций для сдвига
k = int(input('Введи K: '))
# Создаём пустой список
ListAppend = []
# Заполняем список случайными числами
t = 0
while t < n:
    ListAppend.append(random.randint(-100, 100))
    t += 1
# Выводим исходный список
print('Исходный массив:')
print(ListAppend)
# Начинаем сдвиг элементов вправо
i = n - 1
while i >= k:
    # Перемещаем элемент на K позиций вправо
    ListAppend[i] = ListAppend[i - k]
    # Переходим к предыдущему элементу
    i -= 1
# Заполняем первые K элементов нулями
i = 0
while i < k:
    ListAppend[i] = 0
    i += 1
# Выводим полученный список
print('Полученный список:')
print(ListAppend)