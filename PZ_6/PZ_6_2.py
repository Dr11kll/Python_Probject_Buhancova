# Дан список размера N. Найти максимальный из его локальных минимумов
# (локальный минимум — это элемент, который меньше любого из своих соседей).
import random
# Вводим размер списка
N = int(input('Введи размер массива: '))
# Создаём пустой список
a = []
# Вводим элементы списка
for i in range(N):
    x = int(input("Введите элемент: "))
    a.append(x)
# Создаём переменную для максимального локального минимума
maximum = None
# Проверяем элементы, у которых есть два соседа
for i in range(1, N - 1):
    # Проверяем, меньше ли элемент обоих соседей
    if a[i] < a[i - 1] and a[i] < a[i + 1]:
        # Если это первый найденный локальный минимум
        if maximum == None:
            maximum = a[i]
        # Иначе сравниваем с предыдущим максимумом
        elif a[i] > maximum:
            maximum = a[i]
# Выводим результат
if maximum == None:
    print("Локальных минимумов нет")
else:
    print("Максимальный локальный минимум:", maximum)