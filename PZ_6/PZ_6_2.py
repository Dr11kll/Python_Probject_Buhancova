# Задача 2
# Дан список размера N. Найти максимальный из его локальных минимумов
# (локальный минимум — это элемент, который меньше любого из своих соседей).
import random
# Вводим размер списка
n = int(input('Введи размер массива: '))
# Создаём пустой список
ListAppend = []
# Заполняем список случайными числами
t = 0
while t < n:
    ListAppend.append(random.randint(-100, 100))
    t += 1
# Выводим исходный список
print('Исходный массив:')
print(ListAppend)
# Переменная для хранения максимального локального минимума
max_min = 0
# Проверяем, найден ли локальный минимум
found = False
# Начинаем проверку со второго элемента
i = 1
while i < n - 1:
    # Проверяем, меньше ли элемент обоих соседей
    if ListAppend[i] < ListAppend[i - 1] and ListAppend[i] < ListAppend[i + 1]:
        # Если это первый локальный минимум
        if found == False:
            max_min = ListAppend[i]
            found = True
        # Если найденный минимум больше предыдущего
        elif ListAppend[i] > max_min:
            max_min = ListAppend[i]
    # Переходим к следующему элементу
    i += 1
# Выводим результат
if found:
    print('Максимальный из локальных минимумов:', max_min)
else:
    print('Локальные минимумы отсутствуют')