# Даны целые числа N (>2), A и B. Сформировать и вывести целочисленный список
# размера 10, первый элемент которого равен A, второй равен B, а каждый
# последующий элемент равен сумме всех предыдущих.
# Вводим исходные данные
n = int(input('Введи N: '))
a = int(input('Введи A: '))
b = int(input('Введи B: '))
# Создаём список из первых двух элементов
ListAppend = [a, b]
# Вычисляем сумму первых двух элементов
s = a + b
# Начинаем заполнение списка с третьего элемента
t = 2
while t < 10:
    # Добавляем сумму всех предыдущих элементов
    ListAppend.append(s)
    # Учитываем новый элемент в общей сумме
    s += ListAppend[t]
    # Переходим к следующему элементу
    t += 1
# Выводим полученный список
print('Полученный список:', ListAppend)