# Дана строка-предложение на русском языке. Зашифровать ее, выполнив
# циклическую замену каждой буквы на следующую за ней в алфавите и сохранив при
# этом регистр букв («А» перейдет в «Б», «а» — в «б», «Б» — в «В», «я» — в «а» и т.
# д.). Букву «ё» в алфавите не учитывать («е» должна переходить в «ж»). Знаки
# препинания и пробелы не изменять.
# Русский алфавит в нижнем регистре без буквы ё
ABC = "абвгдежзийклмнопрстуфхцчшщъыьэюя"
# Русский алфавит в нижнем регистре без буквы Ё
ABC_BIG = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
S = input("Введите предложение: ")
# Создаем пустую строку для зашифрованного предложения
New_S = ""
# Переберем все символы исходной строки
for i in range(len(S)):
    # Получаем текущий символ
    C = S[i]
    # Если символ есть в алфавите нижнего регистра
    if C in ABC:
        # Находим позицию символа в алфавите
        j = ABC.find(C)
        # Переходим к следующей букве
        j = (j + 1) % len(ABC)
        # Добавляем букву в результат
        New_S += ABC[j]
    # Если буква в верехнем регистре
    elif C in ABC_BIG:
        # Находим ее индекс
        j = ABC_BIG.find(C)
        # Переходим к следующей букве
        j = (j + 1) % len(ABC_BIG)
        # Добавляем новую букву в результат
        New_S += ABC_BIG[j]
    else:
        New_S += C
print("Исходная строка: ", S)
print("Зашифрованная строка: ", New_S)