# Смоделировать простейший калькулятор, умеющий выполнять 4 основные арифметические операции
# Запрос первого числа с проверкой корректности ввода
a = input("Введите первое число: ")
while not type(a) == int:
    try:
        a = int(a)  # Попытка преобразования строки в целое число
    except ValueError:
        print("Ошибка: неправильно ввели число!")  # Сообщение при неверном вводе
        a = input("Введите первое число: ")  # Повторный запрос

# Запрос второго числа с проверкой корректности ввода
b = input("Введите второе число: ")
while not type(b) == int:
    try:
        b = int(b)  # Попытка преобразования строки в целое число
    except ValueError:
        print("Ошибка: неправильно ввели число!")  # Сообщение при неверном вводе
        b = input("Введите второе число: ")  # Повторный запрос

# Запрос операции
operation = input("Введите операцию (+, -, *, /): ")

# Выполнение операции в зависимости от введённого символа
if operation == "+":
    result = a + b
    print(f"Результат: {result}")
elif operation == "-":
    result = a - b
    print(f"Результат: {result}")
elif operation == "*":
    result = a * b
    print(f"Результат: {result}")
elif operation == "/":
    if b != 0:  # Проверка на деление на ноль
        result = a / b
        print(f"Результат: {result}")
    else:
        print("Ошибка: деление на ноль невозможно!")
else:
    print("Ошибка: неверная операция!")
