# Даны два целых А, В. Проверьте истинность высказывания: "Хотя бы одного из чисел А и В четное"
# Ввод первого числа с проверкой корректности
a = input("Введите первое число: ")
while not type(a) == int:
    try:
        a = int(a) # Попытка преобразования введенной строки в целое число
    except ValueError:
        print("Ошибка: неправильно ввели число!") # Сообщение об ошибке при неверном вводе
        a = input("Введите первое число: ") # Повторный запрос ввода
# Ввод второго числа с проверкой корректности
b = input("Введите второе число: ")
while not type(b) == int:
    try:
        b = int(b) # Попытка преобразования введенной строки в целое число
    except ValueError:
        print("Ошибка: неправильно ввели число!")
        b = input("Введите второе число: ")
# Проверка условия: хотя бы одного из чисел четное (остаток от деления на 2 равен 0)
if a % 2 == 0 or b % 2 == 0:
    print("Хотя бы одно из чисел четное")
else:
    print("Оба числа нечетные")
