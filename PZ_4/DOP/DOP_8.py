# Задача 8
# Даны два целых числа А и В (А < В). Найти сумму всех целых чисел от А до В
# включительно (использовать оператор цикла).
a = int(input("Введите A: "))
b = int(input("Введите B: "))
while a >= b:
    print("A должно быть меньше B!")
    a = int(input("Введите A: "))
    b = int(input("Введите B: "))
i = a
s = 0
while i <= b:
    s += i
    i += 1
print("Сумма чисел:", s)