# Вывести первые N (N≥3) чисел Фибоначчи и посчитать количество четных чисел.
n = int(input("Введите N (N >= 3): "))
while n < 3:
    print("N должно быть не меньше 3!")
    n = int(input("Введите N: "))
a = 0
b = 1
i = 1
k = 0
while i <= n:
    print(a)
    if a % 2 == 0:
        k += 1
    c = a + b
    a = b
    b = c
    i += 1
print("Количество чётных чисел:", k)