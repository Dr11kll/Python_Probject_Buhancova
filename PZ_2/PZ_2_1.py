# Дано расстояние L в сантиметрах. Используя операцию деления нацело, найти количество полных метров в нем 1 метр= 100см
try:
    # Ввод данных
    L = int(input("ВВедите расстояние в сантиметрах: "))
    # Вычислене количества полных метров (целочисленное деление)
    meters = L // 100
    print(f"Количество полных метров: {meters}")
except ValueError:
    print("Ошибка: пожалуйста, введите целое число (только цифры).")