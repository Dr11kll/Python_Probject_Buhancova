# Описать функцию InvertDigits(K), меняющую порядок следования цифр целого
# положительного числа K на обратный (K - параметр целого типа, являющийся
# одновременно входным и выходным). С помощью этой функции поменять порядок следования
# цифр на обратный для каждого из пяти данных целых чисел.
# функция меняет порядок цифр числа на обратный
def InvertDigits(K):
    # переменная для хранения перевёрнутого числа
    result = 0
    # пока в числе остаются цифры
    while K > 0:
        # получаем последнюю цифру числа
        digit = K % 10
        # добовляем цифру к новому числу
        result = result * 10 + digit
        # убираем последнюю цифру из исходного числа
        K = K // 10
    # возвращаем перевёрнутое число
    return result
# повторяем ввод и обработку 5 чисел
for i in range(5):
    try:
        # вводим целое пооложительное число
        K = int(input("Введите положительное число: "))
        # проверяем правильность ввода
        if K > 0:
            # вызываем функцию и выводим результат
            print("Число наоборот:", InvertDigits(K))
        else:
            print("Ошибка! Число должно быть положительным.")
    except ValueError:
        # обрабатываем ошибку неправильного ввода
        print("Ошибка! Необходимо ввести целое число.")

