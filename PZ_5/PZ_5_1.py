# Составить функцию, которая выведет на экран строку, содерзащую задеваемое с клавиатуры число символов.
# Функция выводит строку из зданного количества
def printSymbols(n):
# Проверяем, что количсетво символов положительное
    if n > 0:
        print("*" * n)
    else:
        print("Количество символов должно быть больше 0")
# Вводим количество символов с клавиатуры
try:
    n = int(input("Введите количсество символов: ")) #Вызываем функцию
    printSymbols(n)
except ValueError:
    # Обрабатываем ошибку, если введено не целое число
    print("Ошибка! введите цело числою. ")

